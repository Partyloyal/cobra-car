/**
 * دالة استرجاع ألوان الهيكل الخارجي الخاصة بماركة معينة مع دمج الألوان العامة
 */
export function getExteriorColorsForBrand(brandNameOrId: string): ExteriorColorOption[] {
  const brand = CAR_BRANDS.find(
    (b) => b.id === brandNameOrId || b.nameAr === brandNameOrId || b.nameEn.toLowerCase() === brandNameOrId.toLowerCase()
  );

  const brandColors = brand?.exteriorColors || [];
  // Return brand colors first, followed by universal options that don't duplicate hex
  const existingHexes = new Set(brandColors.map((c) => c.hex.toLowerCase()));
  const extraUniversals = UNIVERSAL_EXTERIOR_COLORS.filter((u) => !existingHexes.has(u.hex.toLowerCase()));

  return [...brandColors, ...extraUniversals];
}
